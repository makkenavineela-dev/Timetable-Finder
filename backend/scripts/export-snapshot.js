// Writes frontend/data.js: a copy of the timetable graph that the page uses when it is opened
// without the backend (double-clicking frontend/index.html). Run it after the data changes:
//   npm run export-snapshot
import '../src/env.js';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { read, close, explain } from '../src/db.js';

const OUT = fileURLToPath(new URL('../../frontend/data.js', import.meta.url));

const QUERIES = {
  departments: 'MATCH (d:Department) RETURN d.id AS id, d.name AS name ORDER BY id',
  buildings: 'MATCH (b:Building) RETURN b.id AS id, b.name AS name ORDER BY id',
  floors: `MATCH (b:Building)-[:HAS_FLOOR]->(f:Floor)
RETURN f.id AS id, b.id AS building, f.number AS number ORDER BY building, number`,
  rooms: `MATCH (f:Floor)-[:HAS_ROOM]->(r:Room)
RETURN r.id AS id, r.number AS number, f.id AS floor, r.type AS type, r.capacity AS capacity ORDER BY floor, number`,
  days: 'MATCH (d:Day) RETURN d.id AS id, d.name AS name, d.order AS `order`, d.working AS working ORDER BY `order`',
  grids: 'MATCH (g:TimeGrid) RETURN g.id AS id, g.name AS name, g.default AS `default` ORDER BY id',
  slots: `MATCH (g:TimeGrid)-[:HAS_SLOT]->(t:TimeSlot)<-[:HAS_SLOT]-(d:Day)
RETURN t.id AS id, g.id AS grid, d.id AS day, t.period AS period, left(toString(t.start), 5) AS start, left(toString(t.end), 5) AS end
ORDER BY grid, d.order, t.period`,
  // sample = true marks a section as demo data on screen (code = 'SAMPLE' in the database)
  sections: `MATCH (d:Department)-[:OFFERS]->(p:Program)-[:HAS_ACADEMIC_YEAR]->(ay:AcademicYear)
      -[:HAS_SEMESTER]->(sem:Semester)-[:HAS_SECTION]->(sec:Section)
OPTIONAL MATCH (fc:FacultyCluster)-[:HAS_SECTION]->(sec)
OPTIONAL MATCH (sec)-[:FOLLOWS]->(g:TimeGrid)
RETURN sec.id AS id, sec.name AS name, d.id AS department, p.name AS program, ay.year AS year,
       sem.number AS semester, sem.id AS semesterId, fc.name AS cluster, g.id AS grid, sec.code = 'SAMPLE' AS sample
ORDER BY department, year, semester, name, id`,
  faculty: `MATCH (f:Faculty)-[:WORKS_IN]->(d:Department)
RETURN f.id AS id, f.initials AS initials, f.name AS name, d.id AS department ORDER BY initials, id`,
  courses: `MATCH (c:Course)
RETURN c.code AS code, c.short AS short, c.name AS name, c.LTP AS LTP, c.credits AS credits,
       c.scheduling AS scheduling,
       reduce(n = 0, x IN [(c)-[q:HAS_LTP]->() | q.classesPerWeek] | n + x) AS needed
ORDER BY short, code`,
  allotments: `MATCH (sec:Section)-[:HAS_ALLOTMENT]->(a:Allotment)-[:OF_COURSE]->(c:Course)
OPTIONAL MATCH (f:Faculty)-[:TEACHES {role:'COURSE_TEACHER'}]->(a)
RETURN sec.id AS section, c.code AS course, collect(f.id) AS teachers ORDER BY section, course`,
  // every class of a section; the ones outside an allotment (the Friday seminar) have course null
  classes: `MATCH (cl:Class)-[:FOR_SECTION]->(sec:Section)
OPTIONAL MATCH (a:Allotment)-[:HAS_CLASS]->(cl)
OPTIONAL MATCH (a)-[:OF_COURSE]->(c:Course)
OPTIONAL MATCH (cl)-[:OF_TYPE]->(lt:LTP)
OPTIONAL MATCH (cl)-[:AT_TIME]->(t:TimeSlot)
WITH cl, sec, c, lt, t ORDER BY t.period
WITH cl, sec, c, lt, collect(t.id) AS slots
OPTIONAL MATCH (cl)-[:IN_ROOM]->(r:Room)
WITH cl, sec, c, lt, slots, r ORDER BY r.id
WITH cl, sec, c, lt, slots, collect(r.id) AS rooms
OPTIONAL MATCH (cl)-[:TAUGHT_BY]->(f:Faculty)
WITH cl, sec, c, lt, slots, rooms, f ORDER BY f.id
WITH cl, sec, c, lt, slots, rooms, collect(DISTINCT f.id) AS faculty
OPTIONAL MATCH (cl)-[:FOR_BATCH]->(b:Batch)-[:ASSIGNED_TO]->(bf:Faculty)
WITH cl, sec, c, lt, slots, rooms, faculty, b, bf ORDER BY b.name
RETURN cl.id AS id, cl.name AS name, sec.id AS section, c.code AS course, lt.code AS type,
       rooms, slots, faculty,
       [x IN collect(CASE WHEN b IS NULL THEN null ELSE {name: b.name, faculty: bf.id} END) WHERE x IS NOT NULL] AS batches
ORDER BY id`
};

async function main() {
  const data = {};
  for (const [name, query] of Object.entries(QUERIES)) data[name] = await read(query);
  if (!data.slots.length || !data.sections.length || !data.grids.length) {
    throw new Error('The database has no timetable. Load it first with: npm run load-data');
  }
  fs.writeFileSync(OUT,
    '// Snapshot of the Neo4j timetable graph (generated by backend/scripts/export-snapshot.js).\n' +
    '// Used when the page is opened without the backend. A section with sample: true is demo data.\n' +
    `window.TT_DATA = ${JSON.stringify(data)};\n`);
  console.log(`Wrote ${OUT}: ` + Object.entries(data).map(([k, v]) => `${v.length} ${k}`).join(', '));
}

main()
  .catch((err) => {
    console.error(`Export failed. ${explain(err) || err.message}`);
    process.exitCode = 1;
  })
  .finally(close);
